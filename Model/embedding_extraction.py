def clean_report(text):
    """
    Minimal cleaning.
    Keeps negation and medical terms intact.
    """
    text = str(text)
    text = text.replace("\n", " ")
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def extract_sections(report):
    """
    Extract FINDINGS and IMPRESSION sections if present.
    Falls back to full report otherwise.
    """
    report_upper = report.upper()

    findings = ""
    impression = ""

    if "FINDINGS:" in report_upper:
        findings = report_upper.split("FINDINGS:")[1]
        if "IMPRESSION:" in findings:
            findings = findings.split("IMPRESSION:")[0]

    if "IMPRESSION:" in report_upper:
        impression = report_upper.split("IMPRESSION:")[1]

    combined = findings + " " + impression

    if combined.strip() == "":
        combined = report

    return clean_report(combined)

"""## Load RadBERT Model"""

MODEL_NAME = "zzxslp/RadBERT-RoBERTa-4m"
BATCH_SIZE = 16
MAX_LENGTH = 512

OUPUT_PATH = "report_embeddings.h5"
ID_COLUMN = "note_id"
