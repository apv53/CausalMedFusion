all_embeddings = []
valid_ids = []

with torch.no_grad():
    for i in tqdm(range(0, len(reports), BATCH_SIZE)):

        batch_texts = reports[i:i+BATCH_SIZE]
        batch_ids = note_ids[i:i+BATCH_SIZE]  # FIXED

        processed = []
        kept_ids = []

        for nid, rpt in zip(batch_ids, batch_texts):
            try:
                rpt = extract_sections(rpt)
                processed.append(rpt)          # ONLY append report
                kept_ids.append(nid)           # append ID separately
            except:
                continue

        if len(processed) == 0:
            continue

        inputs = tokenizer(
            processed,
            padding=True,
            truncation=True,
            max_length=MAX_LENGTH,
            return_tensors="pt"
        )

        inputs = {k: v.to(device) for k, v in inputs.items()}

        outputs = model(**inputs)

        cls_embeddings = outputs.last_hidden_state[:, 0, :]
        cls_embeddings = torch.nn.functional.normalize(cls_embeddings, dim=-1)

        all_embeddings.append(cls_embeddings.cpu())
        valid_ids.extend(kept_ids)

# Concatenate
