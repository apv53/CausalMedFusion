with torch.no_grad():
    for i in tqdm(range(0, len(CXR_paths), BATCH_SIZE)):

        batch_paths = CXR_paths[i: i+BATCH_SIZE]
        batch_ids = dicom_ids[i: i+BATCH_SIZE]

        images = []
        kept_ids = []

        for dicom_id, path in zip(batch_ids, batch_paths):
            try:
                img = preprocess_image(path)
                images.append(img)
                kept_ids.append(dicom_id)
            except Exception as e:
                failed_paths.append(path)
                failed_ids.append(dicom_id)

        if len(images) == 0:
            continue

        images = torch.stack(images).to(device)

        features = model.features(images)
        pooled = torch.nn.functional.adaptive_avg_pool2d(features, (1,1))
        pooled = pooled.view(pooled.size(0), -1)
        pooled = torch.nn.functional.normalize(pooled, dim=-1)

        all_embeddings.append(pooled.cpu())
        valid_ids.extend(kept_ids)

all_embeddings = torch.cat(all_embeddings, dim=0).numpy()

