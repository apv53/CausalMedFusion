"""### Image Preprocessing"""

import torch.nn.functional as F

def preprocess_image(path):

    # Load image as numpy array (grayscale)
    img = Image.open(path).convert("L")
    img = np.array(img)

    # Normalize using XRV (expects numpy)
    img = xrv.datasets.normalize(img, maxval=255)

    # Convert to torch tensor
    img = torch.tensor(img).unsqueeze(0)  # (1, H, W)

    # Resize to 224x224
    img = F.interpolate(
        img.unsqueeze(0),
        size=(224, 224),
        mode="bilinear",
        align_corners=False
    ).squeeze(0)

    return img

"""### Load DenseNet Model"""

BATCH_SIZE = 16
